def summarize_database(database_config):
    engine = database_config.get('ENGINE', '')
    if engine == 'django.db.backends.sqlite3':
        return f"SQLite ({database_config.get('NAME')})"
    return (
        f"{engine} "
        f"(name={database_config.get('NAME')}, "
        f"host={database_config.get('HOST', '')}, "
        f"port={database_config.get('PORT', '')})"
    )


