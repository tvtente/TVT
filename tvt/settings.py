def config(name, default=_UNSET, cast=str):
    """
    Unified config accessor.
    - production: only reads process environment variables.
    - development/testing: reads env variables with .env fallback via decouple.
    """
    if ENVIRONMENT == 'production':
        raw = os.environ.get(name)
        if raw is None:
            if default is _UNSET:
                raise ValueError(f"Missing required environment variable: {name}")
            return cast(default) if cast is not None else default
        return cast(raw) if cast is not None else raw

    if default is _UNSET:
        return file_config(name, cast=cast)
    return file_config(name, default=default, cast=cast)


