MYSQL_ENGINES = {'django.db.backends.mysql'}


def _is_path_like_db_name(value):
    value = str(value or '')
    return '/' in value or '\\' in value or value.endswith('.sqlite3')


def build_mysql_database_from_env(engine='django.db.backends.mysql'):
    database_config = {
        'ENGINE': engine,
        'NAME': config('DB_NAME'),
        'USER': config('DB_USER'),
        'PASSWORD': config('DB_PASSWORD'),
        'HOST': config('DB_HOST', default='localhost'),
        'PORT': config('DB_PORT', default='3306'),
        'OPTIONS': {
            'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
            'charset': 'utf8mb4',
        }
    }
    test_db_name = config('DB_TEST_NAME', default='').strip()
    if test_db_name:
        database_config['TEST'] = {'NAME': test_db_name}
    return database_config

